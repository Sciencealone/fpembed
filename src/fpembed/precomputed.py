"""Stateless compression of embeddings produced outside fpembed.

A :class:`PrecomputedEmbeddingCompressor` wraps an external embedding model
(for example a foundation model or CLAMP) without adding that model to the
dependency set. It applies an optional caller-supplied centering vector, an
optional per-row L2 normalization, and the same projection kernels the
generator uses. It never fits, trains, or persists anything.

Public API
----------
PrecomputedEmbeddingCompressor : Compress an external ``(N, input_dim)`` matrix.
"""

from __future__ import annotations

from typing import Any

import numpy as np
import numpy.typing as npt

from fpembed.compression import (
    _is_power_of_two,
    _validate_method_params,
)
from fpembed.compression_projection import (
    compress_hadamard,
    compress_random_projection,
)
from fpembed.docs_links import with_docs
from fpembed.dtype_support import cast_output, normalize_dtype
from fpembed.generator_support import (
    extract_supplied_matrix,
    prepare_projection_artifacts,
)
from fpembed.hashing import fp_params_hash
from fpembed.input_validation import validate_real_finite_input
from fpembed.manifest import build_precomputed_manifest
from fpembed.matrix_identity import array_id

_ACTIVE_METHODS = ("random_projection", "hadamard")
_NORMALIZATIONS = ("none", "l2")


class PrecomputedEmbeddingCompressor:
    """Compress fixed-length embeddings generated by an external model.

    ``center`` is supplied by the caller and is applied before ``normalize``.
    An all-zero row stays zero under ``"l2"``. Compression is limited to the
    projection methods, and the class never fits or persists anything.
    """

    __slots__ = (
        "_input_dim", "_compression", "_source_id", "_method",
        "_method_params", "_projection_cache", "_dtype", "_normalize",
        "_center", "_center_id", "_params_hash",
    )

    def __init__(
        self,
        input_dim: int,
        compression: int | None,
        source_id: str,
        method: str | None = None,
        method_params: dict | None = None,
        dtype: Any = np.float64,
        normalize: str = "none",
        center: npt.ArrayLike | None = None,
    ) -> None:
        if isinstance(input_dim, bool) or not isinstance(input_dim, int):
            raise TypeError(
                with_docs(
                    f"input_dim must be an int, got {type(input_dim).__name__}",
                    "precomputed-argument-type",
                )
            )
        if input_dim <= 0:
            raise ValueError(
                with_docs(
                    f"input_dim must be positive, got {input_dim}",
                    "precomputed-argument-value",
                )
            )

        if not isinstance(source_id, str) or not source_id.strip():
            raise ValueError(
                with_docs(
                    "source_id must be a non-empty string identifying the model "
                    "or checkpoint that produced the embeddings.",
                    "precomputed-source-id-empty",
                )
            )

        if compression is not None:
            if isinstance(compression, bool) or not isinstance(compression, int):
                raise TypeError(
                    with_docs(
                        "compression must be an int or None, got "
                        f"{type(compression).__name__}",
                        "precomputed-argument-type",
                    )
                )
            if compression < 0:
                raise ValueError(
                    with_docs(
                        f"compression must be >= 0, got {compression}",
                        "precomputed-argument-value",
                    )
                )
        effective = 0 if (compression is None or compression == 0) else compression
        if effective != 0:
            if not _is_power_of_two(effective):
                raise ValueError(
                    with_docs(
                        f"compression must be a power of 2, got {effective}",
                        "precomputed-compression-power-of-two",
                    )
                )
            if effective > input_dim / 2:
                raise ValueError(
                    with_docs(
                        f"compression ({effective}) must be <= input_dim / 2 "
                        f"({input_dim // 2})",
                        "precomputed-compression-half",
                    )
                )
            if input_dim % effective != 0:
                raise ValueError(
                    with_docs(
                        f"input_dim ({input_dim}) must be evenly divisible by "
                        f"compression ({effective})",
                        "precomputed-input-dim-divisible",
                    )
                )

        if normalize not in _NORMALIZATIONS:
            raise ValueError(
                with_docs(
                    f"normalize must be one of {_NORMALIZATIONS}, got {normalize!r}",
                    "precomputed-normalize",
                )
            )

        try:
            normalized_dtype = normalize_dtype(dtype)
        except ValueError as exc:
            raise ValueError(
                with_docs(
                    "dtype must be float64 or float32 for precomputed embeddings; "
                    "uint16 and integer types are not supported.",
                    "precomputed-dtype",
                )
            ) from exc
        if normalized_dtype.type is np.uint16:
            raise ValueError(
                with_docs(
                    "dtype='uint16' is not supported for precomputed embeddings: "
                    "external values are continuous. Use float64 or float32.",
                    "precomputed-dtype",
                )
            )

        center_array = None
        center_id = None
        if center is not None:
            center_array = np.asarray(center)
            validate_real_finite_input(center_array)
            if center_array.ndim != 1 or center_array.shape[0] != input_dim:
                raise ValueError(
                    with_docs(
                        f"center must be a vector of length input_dim "
                        f"({input_dim}); got shape {center_array.shape}.",
                        "precomputed-center-length",
                    )
                )
            center_array = np.ascontiguousarray(center_array, dtype=np.float64)
            center_id = array_id(center_array)

        method_params = dict(method_params) if method_params else {}
        if effective == 0:
            method = None
            stored_method_params: dict = {}
            supplied_matrix = None
        else:
            if method is None:
                method = "random_projection"
            if method not in _ACTIVE_METHODS:
                raise ValueError(
                    with_docs(
                        f"Precomputed compression supports only "
                        f"{', '.join(_ACTIVE_METHODS)}; got '{method}'.",
                        "precomputed-method",
                    )
                )
            _validate_method_params(method, method_params)
            output_dim = input_dim // effective
            if method == "hadamard" and not (
                _is_power_of_two(input_dim) and _is_power_of_two(output_dim)
            ):
                raise ValueError(
                    with_docs(
                        f"hadamard requires input_dim ({input_dim}) and "
                        f"input_dim // compression ({output_dim}) to be powers of "
                        "two.",
                        "precomputed-hadamard-dimensions",
                    )
                )
            supplied_matrix = None
            stored_method_params = dict(method_params)
            if "matrix" in method_params:
                supplied_matrix, stored_method_params = extract_supplied_matrix(
                    method_params, input_dim, output_dim,
                )

        self._input_dim = input_dim
        self._compression = effective
        self._source_id = source_id
        self._method = method
        self._method_params = stored_method_params
        self._dtype = normalized_dtype
        self._normalize = normalize
        self._center = center_array
        self._center_id = center_id
        self._projection_cache = prepare_projection_artifacts(
            effective, method or "", input_dim, stored_method_params,
            supplied_matrix,
        )

        params = {
            "source_id": source_id,
            "input_dim": input_dim,
            "normalize": normalize,
        }
        if center_id is not None:
            params["center_id"] = center_id
        self._params_hash = fp_params_hash(
            "precomputed", params, method=method,
            method_params=stored_method_params if effective else None,
        )

    # -- properties -------------------------------------------------

    @property
    def input_dim(self) -> int:
        """Feature length of the external embeddings."""
        return self._input_dim

    @property
    def compression(self) -> int:
        """Compression factor (0 means no compression)."""
        return self._compression

    @property
    def source_id(self) -> str:
        """Model or checkpoint identifier."""
        return self._source_id

    @property
    def normalize(self) -> str:
        """Row normalization mode."""
        return self._normalize

    @property
    def params_hash(self) -> str:
        """16-char identity hash of the source, shape, transform, and method."""
        return self._params_hash

    # -- compression ------------------------------------------------

    def _prepare(self, embeddings: npt.ArrayLike) -> npt.NDArray[np.float64]:
        array = np.asarray(embeddings)
        if array.ndim not in (1, 2):
            raise ValueError(
                with_docs(
                    f"Input must be 1-D (input_dim,) or 2-D (N, input_dim) with "
                    f"input_dim={self._input_dim}; got shape {array.shape}.",
                    "precomputed-compression-input",
                )
            )
        if array.shape[-1] != self._input_dim:
            raise ValueError(
                with_docs(
                    f"Input feature axis must equal input_dim "
                    f"({self._input_dim}); got shape {array.shape}.",
                    "precomputed-input-feature-axis",
                )
            )
        validate_real_finite_input(array)
        work = array.astype(np.float64, copy=True)
        if self._center is not None:
            work -= self._center
        if self._normalize == "l2":
            norms = np.linalg.norm(work, axis=-1, keepdims=True)
            np.divide(work, norms, out=work, where=norms > 0)
        return work

    def _compress_prepared(
        self, work: npt.NDArray[np.float64],
    ) -> npt.NDArray[Any]:
        if self._compression == 0:
            return cast_output(work, self._dtype)
        single = work.ndim == 1
        if not single and work.shape[0] == 0:
            output_dim = self._input_dim // self._compression
            empty = np.empty((0, output_dim), dtype=np.float64)
            return cast_output(empty, self._dtype)
        if self._method == "hadamard":
            out = compress_hadamard(
                work, self._compression, self._projection_cache
            )
        else:
            out = compress_random_projection(
                work, matrix_t=self._projection_cache
            )
        if single:
            out = out[0]
        return cast_output(out, self._dtype)

    def compress(self, embeddings: npt.ArrayLike) -> npt.NDArray[Any]:
        """Compress a ``(N, input_dim)`` matrix or a single vector."""
        return self._compress_prepared(self._prepare(embeddings))

    def compress_one(self, embedding: npt.ArrayLike) -> npt.NDArray[Any]:
        """Compress one ``(input_dim,)`` vector."""
        array = np.asarray(embedding)
        if array.ndim != 1:
            raise ValueError(
                with_docs(
                    f"compress_one expects a 1-D vector of length input_dim "
                    f"({self._input_dim}); got shape {array.shape}.",
                    "precomputed-compression-input",
                )
            )
        return self._compress_prepared(self._prepare(array))

    # -- manifest ---------------------------------------------------

    def representation_manifest(self) -> dict:
        """Return a fresh schema-2 identity of the compressed representation."""
        return build_precomputed_manifest(self)
