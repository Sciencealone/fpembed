def sitemap_urls(found_docs, base_url=html_baseurl):
    """Map document names to absolute page URLs under the published base URL."""
    return [f"{base_url}{name}.html" for name in sorted(found_docs)]


def write_sitemap(app, exception):
    """Write sitemap.xml into the build root after a successful build.

    Read the Docs serves a custom sitemap.xml from the default version's build
    output at the domain root and replaces its autogenerated file, so this is
    the only sitemap that reaches crawlers.
    """
    if exception is not None:
        return
    entries = "\n".join(
        f"  <url><loc>{escape(url)}</loc></url>"
        for url in sitemap_urls(app.env.found_docs, app.config.html_baseurl)
    )
    content = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}\n"
        "</urlset>\n"
    )
    Path(app.outdir, "sitemap.xml").write_text(content, encoding="utf-8")


def setup(app):
    app.connect("build-finished", write_sitemap)
    return {"parallel_read_safe": True, "parallel_write_safe": True}
